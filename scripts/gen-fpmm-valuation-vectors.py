#!/usr/bin/env python3
"""Generates tests/fixtures/fpmm-valuation.json.

Run:  python3 scripts/gen-fpmm-valuation-vectors.py > tests/fixtures/fpmm-valuation.json

The functions below are a line-for-line transcription of `gross_for_shares`,
`collateral_out_for_shares` and `calc_sell` in model/fpmm_model.py of the
contracts repo (OracleDesk-SmartContract), using Python's exact integers
(`math.isqrt`). The contracts submodule is not checked out in this repo, so the
transcription lives here; when it is, replace the block with
`from model.fpmm_model import collateral_out_for_shares, ...` and regenerate.
"""
import json
import math
import random

BPS = 10_000


def mul_div_floor(a, b, c):
    assert a >= 0 and b >= 0 and c > 0
    return (a * b) // c


def mul_div_ceil(a, b, c):
    assert a >= 0 and b >= 0 and c > 0
    return -((-(a * b)) // c)


def gross_for_shares(r_sold, r_other, shares_in, fee_bps):
    a = shares_in + r_sold
    b = a + r_other
    disc = b * b - 4 * r_other * shares_in
    if disc < 0:
        return None
    root = math.isqrt(disc)
    gross = (b - root) // 2
    if gross <= 0 or gross >= r_other:
        return None
    return gross


def collateral_out_for_shares(r_sold, r_other, shares_in, fee_bps):
    gross = gross_for_shares(r_sold, r_other, shares_in, fee_bps)
    if gross is None:
        return None
    return mul_div_floor(gross, BPS - fee_bps, BPS)


def price_yes_bps(r_yes, r_no):
    return mul_div_floor(r_no, BPS, r_yes + r_no)


rng = random.Random(7810)
vectors = []
fixed = [
    (1_000_000_000, 1_000_000_000, 100, 100_000_000),
    (2_500_000_000, 400_000_000, 200, 50_000_000),
    (400_000_000, 2_500_000_000, 200, 50_000_000),
    (1_000_000_000, 1_000_000_000, 0, 1),
    (5_000_000, 5_000_000, 100, 4_999_999_999),  # illiquid: shares dwarf the pool
]
for r_yes, r_no, fee, shares in fixed:
    vectors.append((r_yes, r_no, fee, shares))
for _ in range(40):
    vectors.append((
        rng.randint(10_000_000, 9_000_000_000_000),
        rng.randint(10_000_000, 9_000_000_000_000),
        rng.choice([0, 30, 100, 200, 500]),
        rng.randint(1_000, 5_000_000_000),
    ))

out = []
for r_yes, r_no, fee, shares in vectors:
    # YES position sells YES into the pool (r_sold = r_yes); NO sells NO.
    out.append({
        "reserveYes": str(r_yes), "reserveNo": str(r_no), "feeBps": fee, "shares": str(shares),
        "priceYesBps": price_yes_bps(r_yes, r_no),
        "yesLiquidation": None if (v := collateral_out_for_shares(r_yes, r_no, shares, fee)) is None else str(v),
        "noLiquidation": None if (v := collateral_out_for_shares(r_no, r_yes, shares, fee)) is None else str(v),
    })

print(json.dumps({
    "_header": "Generated by `python3 scripts/gen-fpmm-valuation-vectors.py > tests/fixtures/fpmm-valuation.json` from a transcription of model/fpmm_model.py collateral_out_for_shares. null = the pool cannot absorb the sale (MathError / illiquid).",
    "vectors": out,
}, indent=1))
